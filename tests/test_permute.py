"""Tests for breaking positional correspondence, per issue #20 and the null control.

`score.positional` measures what a model scores by pairing record n with record
n and reading nothing else: **0.839 correspondence F1 on sealed-v4.** The reason
it scores at all is that the generator emits records in correspondence order on
both sides, so the training corpus rewards the same policy — a model can do well
without ever consulting an amount, a reference or a date.

Permutation removes that reward. Each side's record order is shuffled per case
before identifiers are assigned, so `A-002` may correspond to `B-004` and the
only way to pair them is to read them.

**It is off by default, and that is not timidity.** Turning it on globally would
change what `build` emits for the frozen templates, and sealed-v4 could no
longer be regenerated byte-for-byte from its configuration and seed — which is
the whole of the exam's provenance story. The exam stays position-regular and
the null control is what keeps its numbers honest; training is what varies.
"""

from __future__ import annotations

import json
from pathlib import Path

from consylr.cases import Case
from consylr.score import Answer, positional, score
from consylr.templates import load
from tests.support import a_template, built


def _pairs(case: Case) -> list[tuple[str, str]]:
    return [(m["l"][0], m["r"][0]) for m in case.expected["matches"] if m["l"] and m["r"]]


def test_permutation_breaks_the_positional_answer() -> None:
    """At least one case must pair A-00n with something other than B-00n.

    Checked across several indices rather than one, because a permutation of a
    three-element side lands on the identity often enough that a single case
    would make this test flap.
    """
    broken = False
    for index in range(8):
        case = built(a_template(), case_index=index, permute=True)
        if any(a.split("-")[1] != b.split("-")[1] for a, b in _pairs(case)):
            broken = True
            break

    assert broken, "every permuted case still paired by position"


def test_a_permuted_case_is_still_correct_by_construction() -> None:
    """The answer key has to be right under the permutation, not merely present.

    A permutation applied to the records but not carried into the key would
    produce a corpus that teaches the wrong correspondence — worse than the
    positional regularity it set out to fix.
    """
    for index in range(8):
        case = built(a_template(), case_index=index, permute=True)
        assert case.violations == [], f"case {index}: {case.violations}"


def test_permuting_is_reproducible() -> None:
    """Same seed and index, same packet. A corpus is regenerated, not kept."""
    first = built(a_template(), case_index=3, permute=True)
    second = built(a_template(), case_index=3, permute=True)

    assert json.dumps(first.packet, sort_keys=True) == json.dumps(second.packet, sort_keys=True)


def test_the_exam_is_position_regular_unless_asked_otherwise() -> None:
    """Default off, so sealed-v4 stays regenerable from its config and seed."""
    case = built(a_template(), case_index=3)

    assert all(a.split("-")[1] == b.split("-")[1] for a, b in _pairs(case))


def test_permutation_defeats_the_model_that_reads_nothing() -> None:
    """The measurement that justifies permuting at all.

    `score.positional` pairs record n with record n and consults nothing else.
    Against cases built from these templates it scores 0.809 correspondence F1
    unpermuted — a corpus that rewards the null strategy teaches it — and 0.273
    permuted. The gap is the reward being removed.

    Characterisation: the numbers were measured first and this pins them, so a
    change that quietly restores positional regularity fails here rather than in
    a scorecard three hours later.
    """
    templates = load(Path(__file__).resolve().parent.parent / "templates-train")[::40]
    scored = {}
    for permuted in (False, True):
        answers = [
            Answer(
                packet=case.packet,
                expected=case.expected,
                produced=positional(case.packet),
                family=case.meta["family"],
            )
            for template in templates
            for case in [built(template, case_index=index, permute=permuted) for index in range(6)]
        ]
        scored[permuted] = score(answers).correspondence_f1

    assert scored[False] > 0.7, f"the unpermuted corpus no longer rewards position: {scored}"
    assert scored[True] < 0.45, f"permutation did not remove the reward: {scored}"
